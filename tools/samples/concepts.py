#   '= תווית | $נוסחה$'     - שורה בטבלה (שורות רצופות = טבלה אחת)
#   '↓ $ביטוי$ | הערה'      - שלב בחישוב; שלבים רצופים מחוברים בחצים
#   '@ תגית'                - תגית קטנה (למשל "באופן כללי")
#   'svg:שם'                - שרטוט עם מערכת צירים (diagrams.py)

